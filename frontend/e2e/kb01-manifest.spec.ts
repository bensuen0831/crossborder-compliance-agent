import { safeBrowserError } from "./kb01-safe-evidence";
import { test, expect } from "@playwright/test";
import fs from "node:fs";
import path from "node:path";
import en from "../src/locales/en-US.json" with { type: "json" };

const prefix = "/api/v1/admin/knowledge-management";
const t = (key: keyof typeof en) => en[key];

test("KB01 optional CSV catalogue remains an immutable proposal until explicit file mapping", async ({ page }) => {
  test.setTimeout(180_000);
  expect(process.env.KB01_BROWSER_FIXTURES).toBeTruthy();
  const originals = JSON.parse(fs.readFileSync(process.env.KB01_BROWSER_FIXTURES!, "utf8")) as { locale: string; format: string; path: string; marker: string }[];
  const original = originals.find(row => row.locale === "en-US" && row.format === "TXT")!;
  expect(original).toBeTruthy();
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(safeBrowserError(error.message)));
  page.on("console", message => { if (message.type() === "error") errors.push(safeBrowserError(message.text())); });
  page.on("response", response => { if (response.status() >= 500) errors.push(`HTTP_${response.status()}`); });
  await page.addInitScript(() => { if (["http:", "https:"].includes(location.protocol)) localStorage.setItem("stage1-alpha.ui-locale", "en-US"); });
  expect((await page.request.post("/m0-demo/login", { data: { persona: "A" } })).status()).toBe(200);
  await page.goto("/admin?admin_resource=knowledge-management");
  await page.getByRole("tab", { name: t("ui.kb01.uploads"), exact: true }).click();
  await page.getByLabel(t("ui.kb01.files"), { exact: true }).setInputFiles(original.path);
  await page.getByRole("button", { name: t("ui.kb01.startResume"), exact: true }).click();
  const create = page.getByRole("button", { name: t("ui.kb01.createBatch"), exact: true });
  await expect(create).toBeEnabled({ timeout: 90_000 });
  const creation = page.waitForResponse(response => response.request().method() === "POST" && new URL(response.url()).pathname === prefix + "/import-batches");
  await create.click();
  const batch = await (await creation).json();
  const panel = page.getByRole("region", { name: t("ui.kb01.manifest"), exact: true });
  await panel.getByLabel(t("ui.kb01.manifestFile")).setInputFiles({ name: "optional-catalogue.csv", mimeType: "text/csv", buffer: Buffer.from(`Title,Path\nHuman-reviewed catalogue title,${path.basename(original.path)}\nMissing proposal,missing.txt\nDuplicate A,duplicate.txt\nDuplicate B,duplicate.txt\n`) });
  await panel.getByRole("button", { name: t("ui.kb01.startResume"), exact: true }).click();
  await panel.getByLabel(t("ui.kb01.manifestField.title"), { exact: true }).fill("Title");
  await panel.getByLabel(t("ui.kb01.manifestField.relative_path"), { exact: true }).fill("Path");
  const prepare = panel.getByRole("button", { name: t("ui.kb01.manifestPrepare"), exact: true });
  await expect(prepare).toBeEnabled({ timeout: 90_000 });
  const preparing = page.waitForResponse(response => response.request().method() === "POST" && response.url().endsWith(`/import-batches/${batch.batch_id}/manifests`));
  await prepare.click();
  const response = await preparing;
  expect(response.status()).toBe(201);
  const manifest = await response.json();
  expect(manifest.record_count).toBe(4);
  const proposals = panel.getByRole("button", { name: t("ui.kb01.manifestUseProposal"), exact: true });
  await expect(proposals).toHaveCount(4);
  await expect(proposals.nth(0)).toBeEnabled();
  for (const index of [1, 2, 3]) await expect(proposals.nth(index)).toBeDisabled();
  const before = await (await page.request.get(`${prefix}/import-batches/${batch.batch_id}`)).json();
  expect(before.items).toHaveLength(1);
  expect(before.items[0].knowledge_version_id).toBeNull();
  const reportDownload = page.waitForEvent("download");
  await panel.getByRole("button", { name: t("ui.kb01.manifestMissingReport"), exact: true }).click();
  const report = await reportDownload;
  const reportText = fs.readFileSync((await report.path())!, "utf8");
  expect(reportText).toContain("missing.txt");
  expect(reportText).toContain("duplicate.txt");
  await report.delete();
  await proposals.nth(0).click();
  const source = (await (await page.request.get(prefix + "/sources")).json()).items[0];
  await page.getByRole("combobox", { name: t("ui.kb01.sourceId"), exact: true }).selectOption(source.source_id);
  const versions = (await (await page.request.get(`${prefix}/sources/${source.source_id}/collection-versions`)).json()).items;
  await page.getByRole("combobox", { name: t("ui.kb01.collectionVersion"), exact: true }).selectOption(versions[0].collection_version_id);
  await page.locator("form").filter({ has: page.getByRole("heading", { name: t("ui.kb01.documentMetadata"), exact: true }) }).getByRole("textbox", { name: t("ui.kb01.language"), exact: true }).fill("en");
  const confirmation = page.waitForResponse(value => value.request().method() === "POST" && value.url().endsWith(`/import-batches/${batch.batch_id}/confirm-items`));
  await page.getByRole("button", { name: t("ui.kb01.confirmMapping"), exact: true }).click();
  expect((await confirmation).status()).toBe(200);
  await expect.poll(async () => (await (await page.request.get(`${prefix}/import-batches/${batch.batch_id}`)).json()).status, { timeout: 60_000, intervals: [1000] }).toBe("COMPLETED");
  const saved = await (await page.request.get(`${prefix}/import-batches/${batch.batch_id}`)).json();
  expect(saved.items).toHaveLength(1);
  expect(saved.items[0].manifest_record_id).toBeTruthy();
  const version = await (await page.request.get(`/api/v1/admin/knowledge-versions/${saved.items[0].knowledge_version_id}`)).json();
  const managed = await (await page.request.get(`${prefix}/documents/${version.document_id}`)).json();
  expect(managed.versions.find((row: { knowledge_version_id: string }) => row.knowledge_version_id === version.knowledge_version_id).metadata.title).toBe("Human-reviewed catalogue title");
  expect(version.lifecycle).toBe("INGESTED");
  expect(version.provenance_json.kb01_manifest_record_id).toBe(saved.items[0].manifest_record_id);
  expect(version.provenance_json.kb01_manifest_id).toBe(manifest.manifest_id);
  await page.reload();
  const persisted = await (await page.request.get(`${prefix}/import-batches/${batch.batch_id}/manifests/${manifest.manifest_id}`)).json();
  expect(persisted.record_count).toBe(4);
  expect(errors).toEqual([]);
});
